/** EXIF metadata block. No GPS fields — stripped at process-photos.ts time. */
export type PhotoExif = {
  /** Camera make + model, e.g. "FUJIFILM X-E5". */
  camera?: string
  /** Lens model, e.g. "XF23mmF2 R WR". */
  lens?: string
  /** Fuji film simulation name, e.g. "Classic Chrome". Drives TASK-34 palette suggestion. */
  filmSim?: string
  /** Aperture as f-number, e.g. 2.8. */
  aperture?: number
  /** Shutter speed display string, e.g. "1/250". */
  shutter?: string
  /** ISO value, e.g. 400. */
  iso?: number
  /** Focal length in mm (native), e.g. 23. */
  focal?: number
  /** Focal length equivalent in 35mm, e.g. 35. */
  focal35?: number
  /** ISO 8601 capture time string. */
  captureTime?: string
}

/** A single format entry within a variant size. */
export type PhotoVariantEntry = {
  /** JPEG path, web-root relative. */
  jpg: string
  /** WebP path, web-root relative. */
  webp: string
  /** AVIF path, web-root relative. */
  avif: string
}

/**
 * Responsive variant set. Generated by scripts/process-photos.ts.
 * Three sizes × three formats = 9 output files per source JPEG.
 * Absent if process-photos.ts has not been run yet.
 */
export type PhotoVariants = {
  /** 320px wide. Thumbnails and contact sheet. */
  thumb: PhotoVariantEntry
  /** 1280px wide. Lightbox medium. */
  medium: PhotoVariantEntry
  /** 2400px wide. Full-resolution view. */
  full: PhotoVariantEntry
}

