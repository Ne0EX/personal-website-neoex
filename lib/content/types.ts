/**
 * A typed Globe pin record. Discriminated by `kind` so Sirius can render
 * different glyph shapes per content type (article=circle, photo=square,
 * fiction=diamond) per journey-arch §2.2.
 */
export type GlobePin =
  | ArticlePin
  | PhotoPin
  | FictionPin

export type ArticlePin = {
  kind: 'article'
  fileNum: string
  title: string
  summary: string
  coords: { lat: number; lon: number; place: string }
  /** ISO date for sort. */
  isoDate: string
  domain: string
  status: string
  tags: string[]
}

export type PhotoPin = {
  kind: 'photo'
  roll: string
  id: string
  caption?: string
  /** Only present when shareLocation=true AND coords are defined. */
  coords: { lat: number; lon: number; place: string }
  isoDate: string
  /** Film simulation from EXIF — for TASK-34 palette suggestion on hover. */
  filmSim?: string
  /** Thumbnail variant for Globe hover preview — uses variants.thumb.webp. */
  thumbWebp?: string
}

export type FictionPin = {
  kind: 'fiction'
  slug: string
  title: string
  summary: string
  /** Orbital placement is by meaning-coords (domain + date), not GPS.
   *  Globe placement algorithm lives in TASK-33 (WorldlineGlobe.tsx).
   *  We provide the domain + date so Sirius can compute NeX orbit coords. */
  domain: string
  isoDate: string
  tags: string[]
  /**
   * Alternate-α variant tendrils for this fiction node.
   * Empty array when no variants declared (the node branches only via siblings,
   * or not at all). Sirius reads this at RW-5 drift activation (§13.2 step 2).
   * 30-worldline-branching.md §3.1 (Channel A) + §4.3.
   */
  variants: FictionVariant[]
  /**
   * Divergence cluster label. Undefined when not declared.
   * Build-time sibling computation uses this to group fiction entries.
   * Sirius receives the pre-computed sibling list (getFictionSiblings) rather
   * than computing it in the renderer. 30-worldline-branching.md §3.1 (Channel B).
   */
  divergence_cluster?: string
}

